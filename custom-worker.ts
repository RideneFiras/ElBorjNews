// Worker entry (wrangler.jsonc "main"): wraps the Worker OpenNext generates at build time.
//
// Next.js sends cached (ISR) pages with `Cache-Control: s-maxage=…, stale-while-revalidate=2592000`.
// No shared cache uses s-maxage here (the Cloudflare CDN doesn't cache these pages), but
// browsers honour stale-while-revalidate: with no max-age the saved copy is always stale yet
// inside the 30-day window, so the browser showed the old page and refreshed it in the
// background. New articles only appeared after a hard refresh (docs/DECISIONS.md, 2026-10-19).
// Browsers now get `max-age=0, must-revalidate`: they ask the Worker every time, which answers
// from its own page cache (R2 + Cache API), so this costs no extra page builds.

// @ts-expect-error: generated by `opennextjs-cloudflare build`, resolved by wrangler
import { default as handler } from './.open-next/worker.js';

import { browserCacheControl } from './src/lib/security/browser-cache';

type Fetch = (request: Request, env: unknown, ctx: unknown) => Promise<Response>;

const worker = {
  async fetch(request: Request, env: unknown, ctx: unknown): Promise<Response> {
    const response = await (handler.fetch as Fetch)(request, env, ctx);
    const value = browserCacheControl(response.headers.get('cache-control'));
    if (!value) return response;
    const out = new Response(response.body, response);
    out.headers.set('cache-control', value);
    return out;
  },
};

export default worker;

